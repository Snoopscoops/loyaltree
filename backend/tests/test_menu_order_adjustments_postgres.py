def line(item="latte", qty=1, *, variant=False, price=12.50, line_id=None):
    return {
        "line_id": line_id or uuid4().hex,
        "item_id": item,
        "item_name": item.title(),
        "unit_price": price,
        "line_total": qty * price,
        "quantity": qty,
        "options": [{"public_id": "large", "name": "Large"}] if variant else [],
    }


def original(pg, *items, branch=BRANCH, member="member-a", business=BUSINESS):
    public_id = uuid4().hex
    pg.query(
        """INSERT INTO menu_counter_orders
           (public_id, order_number, business_id, service, branch_public_id,
            branch_name, member_customer_public_id, buyer_name, table_no,
            payment_reference, payment_method, payment_status, total, items)
           VALUES (%s, %s, %s, 'dine-in', %s, 'Main', %s, 'Customer', '7',
                   %s, 'cash', 'unpaid', %s, %s)""",
        (public_id, f"TEST-{public_id[:8]}", business, branch, member, f"PAY-{public_id[:8]}",
         sum(item["line_total"] for item in items), pg.json(items)),
    )
    return public_id


def suborder(pg, parent, *items, request_id=None, business=BUSINESS, branch=BRANCH, role="service_role"):
    payload = {"items": items, "total": sum(item["line_total"] for item in items)}
    return pg.call(CREATE, business, branch, parent, request_id or str(uuid4()), pg.json(payload), ACTOR, role=role)


def void(pg, order, item, *, qty=1, reason="Wrong item", request_id=None, business=BUSINESS, branch=BRANCH,
         role="service_role"):
    return pg.call(VOID, business, branch, order, request_id or str(uuid4()),
                   item["line_id"], qty, reason, ACTOR, role=role)


def transition(pg, order, target, *, business=BUSINESS, branch=BRANCH, reason=None, role="service_role", expected_amount=None):
    if target == "paid" and expected_amount is None:
        expected_amount = state(pg, order)[2]
    return pg.call(MOVE, business, branch, order, target, ACTOR, reason, expected_amount, role=role)


def configure_stock(pg, item, qty, *, variant="*"):
    pg.call("menu_set_daily_servings", BUSINESS, BRANCH, item, variant, qty, False)


def stock(pg, item="latte"):
    return dict(
        (variant, (reserved, consumed))
        for variant, reserved, consumed in pg.query(
            """SELECT variant_key, reserved, consumed FROM menu_daily_servings
               WHERE business_id=%s AND branch_public_id=%s AND item_public_id=%s""",
            (BUSINESS, BRANCH, item),
        )
    )


def state(pg, order):
    return pg.query("SELECT status, payment_status, total FROM menu_counter_orders WHERE public_id=%s", (order,))[0]


def concurrent_calls(*calls):
    """Use independent connections and release both workers at the same time."""
    barrier = Barrier(len(calls))

    def run(call):
        barrier.wait(timeout=5)
        try:
            return call()
        except Exception as exc:
            return exc

    with ThreadPoolExecutor(max_workers=len(calls)) as pool:
        return list(pool.map(run, calls))


def assert_error(pg, code, call):
    with pytest.raises(pg.driver.Error) as error:
        call()
    assert error.value.pgcode == code, error.value


