def test_independent_payments_and_parent_finalization(pg):
    configure_stock(pg, "latte", 20, variant="large")
    configure_stock(pg, "latte", 20)
    parent_item = line(qty=2, variant=True)
    child_item = line(qty=3, variant=True)
    parent = original(pg, parent_item)
    child = suborder(pg, parent, child_item)["order"]["public_id"]
    cancelled = suborder(pg, parent, line(variant=True))["order"]["public_id"]
    transition(pg, cancelled, "cancelled", reason="New order entered twice")

    for target in ("paid", "preparing", "ready"):
        transition(pg, parent, target)
    assert state(pg, child) == ("new", "unpaid", Decimal("37.50"))
    assert_error(pg, "23514", lambda: transition(pg, parent, "completed"))
    assert state(pg, parent) == ("ready", "paid", Decimal("25.00"))
    assert stock(pg) == {"*": (5, 0), "large": (5, 0)}

    assert_error(pg, "23514", lambda: transition(pg, child, "preparing"))
    transition(pg, child, "paid")
    assert_error(pg, "23514", lambda: transition(pg, child, "cancelled", reason="No refund"))
    assert_error(pg, "23514", lambda: void(pg, child, child_item))
    for target in ("preparing", "ready"):
        transition(pg, child, target)
    child_result = transition(pg, child, "completed")
    assert child_result["loyalty_order"] is None
    assert stock(pg) == {"*": (2, 3), "large": (2, 3)}

    close = lambda: transition(pg, parent, "completed")
    outcomes = concurrent_calls(close, close)
    assert all(isinstance(outcome, dict) for outcome in outcomes), outcomes
    assert {outcome["changed"] for outcome in outcomes} == {False, True}
    snapshots = [outcome["loyalty_order"] for outcome in outcomes]
    assert all(snapshot and snapshot["public_id"] == parent for snapshot in snapshots)
    assert all(snapshot["member_customer_public_id"] == "member-a" for snapshot in snapshots)
    assert all(snapshot["total"] == 62.50 for snapshot in snapshots)
    assert state(pg, parent) == ("completed", "paid", Decimal("25.00"))
    assert stock(pg) == {"*": (0, 5), "large": (0, 5)}
    assert pg.query(
        "SELECT order_public_id, settled_total FROM menu_counter_order_finalizations",
    ) == [(parent, Decimal("62.50"))]
    assert_error(pg, "23514", lambda: suborder(pg, parent, line()))
    assert_single_wallet_award(pg, snapshots)


class WalletEventStore:
    """Minimal database adapter for the existing wallet award hook."""

    def __init__(self, pg):
        self.pg = pg
        self.values = None
        self.filters = {}

    def table(self, name):
        assert name == "menu_order_wallet_events"
        return WalletEventStore(self.pg)

    def insert(self, values):
        self.values = values
        return self

    def update(self, values):
        self.values = values
        return self

    def eq(self, key, value):
        self.filters[key] = value
        return self

    def execute(self):
        if self.filters:
            self.pg.query(
                """UPDATE menu_order_wallet_events SET result=%s
                   WHERE order_public_id=%s AND kind=%s AND step=%s""",
                (self.pg.json(self.values["result"]), self.filters["order_public_id"],
                 self.filters["kind"], self.filters["step"]),
                role="service_role",
            )
        else:
            self.pg.query(
                """INSERT INTO menu_order_wallet_events
                   (business_id, order_public_id, customer_public_id, kind, step)
                   VALUES (%(business_id)s, %(order_public_id)s, %(customer_public_id)s, %(kind)s, %(step)s)""",
                self.values,
                role="service_role",
            )


