def test_concurrent_requests_cannot_reserve_stock_twice(pg):
    configure_stock(pg, "latte", 5)
    parent = original(pg, line("water"))
    item = line(qty=3)
    token = str(uuid4())
    create = lambda: suborder(pg, parent, item, request_id=token)
    first, second = concurrent_calls(create, create)
    assert isinstance(first, dict) and isinstance(second, dict), (first, second)
    assert {first["changed"], second["changed"]} == {False, True}
    assert first["order"]["public_id"] == second["order"]["public_id"]
    assert pg.query("SELECT count(*) FROM menu_counter_orders") == [(2,)]
    assert stock(pg) == {"*": (3, 0)}
    assert_error(pg, "23514", lambda: suborder(pg, parent, line(qty=2), request_id=token))


def test_concurrent_parents_cannot_oversell_shared_stock(pg):
    configure_stock(pg, "latte", 3)
    first = original(pg, line("water"))
    second = original(pg, line("water"))
    outcomes = concurrent_calls(
        lambda: suborder(pg, first, line(qty=2)),
        lambda: suborder(pg, second, line(qty=2)),
    )
    assert sum(isinstance(outcome, dict) for outcome in outcomes) == 1, outcomes
    rejected = next(outcome for outcome in outcomes if not isinstance(outcome, dict))
    assert isinstance(rejected, pg.driver.Error) and rejected.pgcode == "23514"
    assert stock(pg) == {"*": (2, 0)}
    assert pg.query("SELECT count(*) FROM menu_counter_orders") == [(3,)]


def test_parent_completion_serializes_with_a_new_suborder(pg):
    parent = original(pg, line("water"))
    for target in ("paid", "preparing", "ready"):
        transition(pg, parent, target)
    completion, child = concurrent_calls(
        lambda: transition(pg, parent, "completed"),
        lambda: suborder(pg, parent, line()),
    )
    assert sum(isinstance(outcome, dict) for outcome in (completion, child)) == 1, (completion, child)
    if isinstance(completion, dict):
        assert isinstance(child, pg.driver.Error) and child.pgcode == "23514"
        assert state(pg, parent)[0] == "completed"
        assert pg.query("SELECT count(*) FROM menu_counter_orders") == [(1,)]
    else:
        assert isinstance(completion, pg.driver.Error) and completion.pgcode == "23514"
        assert state(pg, parent)[0] == "ready"
        assert state(pg, child["order"]["public_id"])[:2] == ("new", "unpaid")


