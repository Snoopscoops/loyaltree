@dataclass(frozen=True)
class Database:
    driver: object
    sql: object
    json: object
    socket: str
    name: str

    def connect(self):
        return self.driver.connect(
            host=self.socket,
            hostaddr="",
            port=os.environ.get("LT_BATCH_A_PG_PORT", "5432"),
            dbname=self.name,
            connect_timeout=5,
            options="-c statement_timeout=10000 -c lock_timeout=5000",
        )

    @contextmanager
    def cursor(self, role=None):
        conn = self.connect()
        try:
            with conn, conn.cursor() as cursor:
                if role:
                    cursor.execute(self.sql.SQL("SET LOCAL ROLE {}").format(self.sql.Identifier(role)))
                yield cursor
        finally:
            conn.close()

    def call(self, fn, *args, role="service_role"):
        placeholders = self.sql.SQL(", ").join(self.sql.Placeholder() for _ in args)
        query = self.sql.SQL("SELECT public.{}({})").format(self.sql.Identifier(fn), placeholders)
        with self.cursor(role) as cursor:
            cursor.execute(query, args)
            return cursor.fetchone()[0]

    def query(self, query, args=(), role=None):
        with self.cursor(role) as cursor:
            cursor.execute(query, args)
            return cursor.fetchall() if cursor.description else None

    def migrate(self, filename):
        conn = self.connect()
        try:
            conn.autocommit = True
            with conn.cursor() as cursor:
                cursor.execute((BACKEND / filename).read_text(encoding="utf8"))
        finally:
            conn.close()


