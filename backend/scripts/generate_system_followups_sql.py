"""Build/check the single atomic follow-ups migration. No database connection."""
from argparse import ArgumentParser
import hashlib
from pathlib import Path


BACKEND = Path(__file__).resolve().parents[1]
SOURCES = ("apple_wallet_delivery.sql", "lt_benefits_coupon_limits.sql", "lt_benefits_email_identity.sql")
OUTPUT = BACKEND / "system_followups_5_9.sql"


def strip_outer_transaction(source, filename):
    lines = source.splitlines(keepends=True)
    begins = [i for i, line in enumerate(lines) if line.strip() == "BEGIN;"]
    commits = [i for i, line in enumerate(lines) if line.strip() == "COMMIT;"]
    if len(begins) != 1 or len(commits) != 1 or begins[0] >= commits[0]:
        raise ValueError(f"{filename}: expected exactly one outer BEGIN/COMMIT")
    first, last = begins[0], commits[0]
    if any(line.strip() and not line.lstrip().startswith("--") for line in lines[:first] + lines[last + 1:]):
        raise ValueError(f"{filename}: SQL found outside the outer transaction")
    return "".join(line for i, line in enumerate(lines) if i not in (first, last)).rstrip() + "\n"


def build_bundle():
    sections = ["""-- Loyalty Tree system follow-ups 5-9: run this ONE file in Supabase SQL Editor.
-- Prerequisites: existing lt_benefits.sql, lt_benefits_upgrade.sql and any
-- lt_benefits_visible_updates.sql upgrade have already been installed.
-- Applies Apple delivery recovery, coupon limits, then verified email identity.
-- Running this migration sends no notifications and does not merge accounts.
-- The entire migration is atomic and rerunnable. Deploy the matching code next.
-- Generated by backend/scripts/generate_system_followups_sql.py; do not edit.
-- Verify source parity: python backend/scripts/generate_system_followups_sql.py --check
BEGIN;
"""]
    for filename in SOURCES:
        raw = (BACKEND / filename).read_bytes()
        digest = hashlib.sha256(raw).hexdigest()
        sections.append(f"\n-- SOURCE BEGIN: {filename}\n-- SHA256: {digest}\n")
        sections.append(strip_outer_transaction(raw.decode("utf-8"), filename))
        sections.append(f"-- SOURCE END: {filename}\n")
    sections.append("\nCOMMIT;\n")
    return "".join(sections)


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the bundle differs from its source migrations")
    args = parser.parse_args()
    expected = build_bundle()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != expected:
            parser.exit(1, "system_followups_5_9.sql is stale; run this script without --check.\n")
        print("Follow-ups SQL bundle matches all source migrations.")
    else:
        OUTPUT.write_text(expected)
        print(f"Generated {OUTPUT.name} from {len(SOURCES)} migrations.")


if __name__ == "__main__":
    main()
