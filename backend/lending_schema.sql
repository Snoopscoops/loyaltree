-- LoyaltyTree Lending / Loan Management v1
-- Run once in Supabase SQL Editor before deploying the patched backend/frontend.
-- Additive only: does not alter loyalty, Wallet, POS, Order Ahead, or Car Lending tables.

begin;

create table if not exists public.lending_borrowers (
    id bigint generated by default as identity primary key,
    public_id text not null unique,
    business_id bigint not null references public.businesses(id) on delete cascade,
    name text not null,
    phone text,
    email text,
    address text,
    id_number text,
    emergency_contact_name text,
    emergency_contact_phone text,
    photo_url text,
    notes text,
    status text not null default 'active' check (status in ('active','inactive','blocked')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.lending_loans (
    id bigint generated by default as identity primary key,
    public_id text not null unique,
    business_id bigint not null references public.businesses(id) on delete cascade,
    borrower_id bigint not null references public.lending_borrowers(id) on delete restrict,
    branch_id bigint references public.branches(id) on delete set null,
    contract_number text not null,
    principal_amount numeric(14,2) not null check (principal_amount > 0),
    interest_rate numeric(8,4) not null default 0 check (interest_rate >= 0),
    total_payable numeric(14,2) not null check (total_payable > 0),
    installment_amount numeric(14,2) not null check (installment_amount > 0),
    installment_count integer not null check (installment_count > 0 and installment_count <= 1000),
    payment_frequency text not null default 'monthly' check (payment_frequency in ('daily','weekly','biweekly','semimonthly','monthly')),
    release_date date not null,
    first_due_date date not null,
    next_due_date date,
    last_payment_date date,
    balance_remaining numeric(14,2) not null check (balance_remaining >= 0),
    days_past_due integer not null default 0 check (days_past_due >= 0),
    status text not null default 'active' check (status in ('active','overdue','fully_paid','defaulted','cancelled')),
    notes text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (business_id, contract_number)
);

create table if not exists public.lending_installments (
    id bigint generated by default as identity primary key,
    public_id text not null unique,
    business_id bigint not null references public.businesses(id) on delete cascade,
    loan_id bigint not null references public.lending_loans(id) on delete cascade,
    installment_number integer not null check (installment_number > 0),
    due_date date not null,
    amount_due numeric(14,2) not null check (amount_due >= 0),
    amount_paid numeric(14,2) not null default 0 check (amount_paid >= 0),
    paid_date date,
    status text not null default 'pending' check (status in ('pending','partial','paid')),
    performance text not null default 'pending' check (performance in ('pending','on_time','delayed','overdue')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (loan_id, installment_number)
);

create table if not exists public.lending_payments (
    id bigint generated by default as identity primary key,
    public_id text not null unique,
    business_id bigint not null references public.businesses(id) on delete cascade,
    loan_id bigint not null references public.lending_loans(id) on delete cascade,
    borrower_id bigint not null references public.lending_borrowers(id) on delete restrict,
    branch_id bigint references public.branches(id) on delete set null,
    receipt_number text not null,
    amount numeric(14,2) not null check (amount > 0),
    payment_date date not null,
    method text,
    reference_number text,
    notes text,
    timeliness text not null default 'on_time' check (timeliness in ('on_time','delayed')),
    balance_before numeric(14,2) not null,
    balance_after numeric(14,2) not null,
    created_at timestamptz not null default now(),
    unique (business_id, receipt_number)
);

create table if not exists public.lending_documents (
    id bigint generated by default as identity primary key,
    public_id text not null unique,
    business_id bigint not null references public.businesses(id) on delete cascade,
    borrower_id bigint references public.lending_borrowers(id) on delete cascade,
    loan_id bigint references public.lending_loans(id) on delete cascade,
    document_type text not null default 'other',
    title text,
    file_url text,
    storage_path text,
    file_name text,
    mime_type text,
    created_at timestamptz not null default now(),
    check (borrower_id is not null or loan_id is not null),
    check (file_url is not null or storage_path is not null)
);

create index if not exists idx_lending_borrowers_business on public.lending_borrowers(business_id, created_at desc);
create index if not exists idx_lending_borrowers_name on public.lending_borrowers(business_id, name);
create index if not exists idx_lending_loans_business_status on public.lending_loans(business_id, status, next_due_date);
create index if not exists idx_lending_loans_borrower on public.lending_loans(borrower_id, created_at desc);
create index if not exists idx_lending_loans_branch on public.lending_loans(branch_id, created_at desc);
create index if not exists idx_lending_installments_loan_due on public.lending_installments(loan_id, due_date);
create index if not exists idx_lending_installments_business_perf on public.lending_installments(business_id, performance, due_date);
create index if not exists idx_lending_payments_business_date on public.lending_payments(business_id, payment_date desc);
create index if not exists idx_lending_payments_loan on public.lending_payments(loan_id, payment_date desc);
create index if not exists idx_lending_documents_loan on public.lending_documents(loan_id, created_at desc);
create index if not exists idx_lending_documents_borrower on public.lending_documents(borrower_id, created_at desc);

