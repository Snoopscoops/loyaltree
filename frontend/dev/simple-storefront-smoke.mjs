// Browser smoke using only fictional menu fixtures; no production request is allowed.
import assert from 'node:assert/strict'
import {chromium} from 'playwright'
const base='http://127.0.0.1:4175'
const browser=await chromium.launch({headless:true})
try {
  const context=await browser.newContext({viewport:{width:390,height:844},serviceWorkers:'block'})
  await context.route('**/*',route=>new URL(route.request().url()).origin===base?route.continue():route.abort())
  const page=await context.newPage(),errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto(base+'/dev/owner-dashboard.html?view=menu&published=1&branch=demo-branch-main')
  const menu=page.locator('.lt-simple-storefront')
  await menu.getByRole('heading',{name:'Daylight Coffee',exact:true}).waitFor({timeout:20000})
  const nav=menu.getByRole('navigation',{name:'Menu navigation'})
  assert.equal(await nav.locator('button').count(),4)
  assert.equal(await nav.locator('svg').count(),4)
  assert.equal(await menu.getByRole('button',{name:/reserve a table|book a place/i}).count(),0)
  const search=menu.getByRole('searchbox',{name:'Search menu'})
  await search.fill('Spanish')
  await menu.getByRole('heading',{name:'Iced Spanish Latte',exact:true}).waitFor()
  assert.equal(await menu.getByRole('heading',{name:'Americano',exact:true}).count(),0)
  console.log('PASS compact menu navigation and search')
  await menu.getByRole('button',{name:'Customize Iced Spanish Latte',exact:true}).click()
  const sheet=menu.locator('dialog.lt-qr-sheet')
  await sheet.waitFor({state:'visible'})
  assert.equal(await sheet.getByRole('button',{name:'Complete required options'}).isDisabled(),true)
  await sheet.getByRole('radio',{name:/Large/}).check()
  const add=sheet.getByRole('button',{name:/Add to cart/})
  assert.equal(await add.isEnabled(),true)
  assert.match(await add.innerText(),/170/)
  await add.click()
  await nav.getByRole('button',{name:/Cart/}).click()
  const cart=menu.locator('.lt-qr-cart')
  await cart.waitFor({state:'visible'})
  await cart.getByText('Iced Spanish Latte',{exact:true}).waitFor()
  assert.match(await cart.innerText(),/Large/)
  assert.match(await cart.innerText(),/170/)
  await cart.getByRole('button',{name:'Close cart',exact:true}).click()
  console.log('PASS required variant, updated price and cart')
  await menu.getByRole('button',{name:'Customize Iced Spanish Latte',exact:true}).click()
  await sheet.getByRole('radio',{name:/Regular/}).check()
  await sheet.getByRole('button',{name:/Add to cart/}).click()
  await nav.getByRole('button',{name:/Cart/}).click()
  assert.equal(await cart.locator('.lt-qr-cart-line').count(),2)
  await cart.getByRole('button',{name:'Close cart',exact:true}).click()
  console.log('PASS independent variant cart lines')
  await search.fill('')
  assert.equal(await menu.getByRole('button',{name:'Butter Croissant sold out',exact:true}).isDisabled(),true)
  await nav.getByRole('button',{name:'Rewards',exact:true}).click()
  await menu.getByRole('dialog',{name:'Connect loyalty card'}).waitFor()
  await menu.getByRole('dialog',{name:'Connect loyalty card'}).getByRole('button',{name:'Close',exact:true}).click()
  console.log('PASS sold-out guard and verified card entry')
  await search.fill('Cinnamon')
  await menu.getByRole('button',{name:'Add Cinnamon Roll',exact:true}).click()
  await nav.getByRole('button',{name:/Cart/}).click()
  await cart.getByText('Cinnamon Roll',{exact:true}).waitFor()
  assert.deepEqual(errors,[])
  console.log('PASS quick add and no page errors')
} finally {await browser.close()}
