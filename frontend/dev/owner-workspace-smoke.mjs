// Local fictional workspace only. Reject all external network requests.
import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const base = 'http://127.0.0.1:4175'
const browser = await chromium.launch({headless:true})
try {
  const context = await browser.newContext({viewport:{width:1440,height:900},acceptDownloads:true,serviceWorkers:'block'})
  await context.route('**/*', route => new URL(route.request().url()).origin===base ? route.continue() : route.abort())
  const page = await context.newPage()
  const failures=[]
  page.on('pageerror', e=>failures.push(e.message))
  const heading = name=>page.getByRole('heading',{name,exact:true}).waitFor({timeout:20000})
  const panel = ()=>page.locator('.lt-ws').first()
  const sidebar = page.locator('.lt-owner-sidebar')
  const nav = async (group,item)=>{
    const button=sidebar.getByRole('button',{name:group,exact:true})
    if(await button.getAttribute('aria-expanded')!=='true')await button.click()
    await sidebar.getByRole('button',{name:item,exact:true}).click()
  }
  await page.goto(base+'/dev/owner-dashboard.html')
  await heading("Today's operations")
  await panel().getByText('₱435.00',{exact:true}).waitFor()
  console.log('PASS home cash summary')
  await nav('Orders & Menu','Menu orders')
  await heading('Menu orders')
  await panel().getByRole('button',{name:/DEMO-001/}).click()
  await panel().getByRole('button',{name:'Start preparing',exact:true}).click()
  await panel().getByRole('button',{name:/DEMO-001.*Preparing/s}).waitFor()
  await panel().getByRole('button',{name:/DEMO-002/}).click()
  assert.equal(await panel().getByRole('button',{name:'Start preparing',exact:true}).count(),0)
  console.log('PASS fictional order progression and unpaid guard')
  await nav('Orders & Menu','Transactions')
  await heading('Transactions')
  await panel().getByRole('button',{name:'Monthly',exact:true}).click()
  await panel().getByRole('button',{name:'Monthly',exact:true,pressed:true}).waitFor()
  await panel().getByRole('button',{name:'Daily',exact:true}).click()
  await panel().getByLabel('Branch',{exact:true}).selectOption('demo-branch-main')
  await panel().getByText('₱595.00',{exact:true}).waitFor()
  await panel().getByRole('button',{name:'Custom',exact:true}).click()
  const download = page.waitForEvent('download')
  await panel().getByRole('button',{name:'Download CSV report',exact:true}).click()
  assert.match((await download).suggestedFilename(),/LoyaltyTree-menu-report-.*\.csv$/)
  console.log('PASS transaction periods, branch and fictional CSV')
  await nav('Home','Analytics')
  await page.getByRole('button',{name:'Customer Intelligence',exact:true}).click()
  await heading('Customer Intelligence')
  await panel().getByRole('button',{name:'Weekly',exact:true}).click()
  await panel().getByRole('heading',{name:'Weekly summary'}).waitFor()
  await panel().getByText('Small cohorts are suppressed.',{exact:true}).waitFor()
  await page.getByRole('button',{name:'Product Intelligence',exact:true}).click()
  await heading('Product Intelligence')
  await panel().getByText('Iced Spanish Latte',{exact:true}).waitFor()
  console.log('PASS nested intelligence and cohort suppression')
  await nav('Orders & Menu','Reservations')
  await heading('Booking settings')
  await page.getByRole('heading',{name:'Booking calendar & requests'}).waitFor()
  await nav('Orders & Menu','Merchant payments')
  await heading('Merchant payments')
  await panel().getByText('Not enabled',{exact:true}).waitFor()
  console.log('PASS booking access and disabled payments')
  await page.setViewportSize({width:390,height:844})
  await page.locator('.lt-owner-menu-button').waitFor({state:'visible'})
  await page.locator('.lt-owner-menu-button').click()
  await sidebar.getByRole('button',{name:'Close navigation'}).waitFor({state:'visible'})
  await sidebar.getByRole('button',{name:'Close navigation'}).click()
  assert.deepEqual(failures,[])
  console.log('PASS mobile navigation; no uncaught page errors')
} finally {await browser.close()}
